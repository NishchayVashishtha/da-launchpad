"""Generate docs/schema-cheatsheet.md: compact table/column list for content authors."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
ds = json.loads((root / "src/data/datasets.json").read_text())
out = ["# Dataset schema cheatsheet (auto-generated by scripts/schema_cheatsheet.py)\n",
       "SQLite dialect. Dates are ISO TEXT. Full details: src/data/datasets.json\n"]
for d in ds:
    out.append(f"\n## {d['id']}\n")
    for t in d["tables"]:
        cols = ", ".join(f"{c['name']}:{c['type']}" for c in t["columns"])
        out.append(f"- **{t['name']}** ({t['rowCount']} rows): {cols}")
    out.append("- FKs: " + "; ".join(f"{r['from']}->{r['to']}" for r in d["relationships"]))
    out.append("- Quality issues: " + " | ".join(d["qualityIssues"]))
    out.append("- Signals (instructor notes): " + " | ".join(d.get("signals", [])))
(root / "docs/schema-cheatsheet.md").write_text("\n".join(out) + "\n")
